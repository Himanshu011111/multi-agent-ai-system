import io
from typing import List
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor


def build_executive_pptx(title: str, content: str, qa_score: float = 85.0) -> bytes:
    """
    Converts a research report into a clean multi-slide PowerPoint (.pptx) deck in memory.
    """
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    # Slide 1: Executive Title Slide
    title_slide = prs.slides.add_slide(prs.slide_layouts[0])
    title_slide.shapes.title.text = title[:90]
    subtitle = title_slide.placeholders[1]
    subtitle.text = (
        f"Generated by Multi-Agent AI Research & RAG Hub\n"
        f"Enterprise Critic QA Verified Score: {qa_score:.0f}/100"
    )

    # Split content into clean slide sections
    raw_blocks = [b.strip() for b in content.split("\n\n") if b.strip()]
    if not raw_blocks:
        raw_blocks = ["Executive summary generated by Multi-Agent AI workflow."]

    slides_data: List[tuple[str, List[str]]] = []
    current_heading = "Executive Overview"
    current_bullets: List[str] = []

    for block in raw_blocks:
        clean_line = block.lstrip("#").strip()
        if block.startswith("#") or (len(clean_line) < 75 and not clean_line.endswith(".")):
            if current_bullets:
                slides_data.append((current_heading, current_bullets))
                current_bullets = []
            current_heading = clean_line[:80]
        else:
            sentences = [s.strip() for s in clean_line.replace("\n", " ").split(". ") if s.strip()]
            for s in sentences[:4]:
                current_bullets.append(s[:220])
            if len(current_bullets) >= 4:
                slides_data.append((current_heading, current_bullets))
                current_bullets = []

    if current_bullets:
        slides_data.append((current_heading, current_bullets))

    # Content Slides (Max 8 slides to keep file crisp)
    bullet_layout = prs.slide_layouts[1]
    for heading, bullets in slides_data[:8]:
        slide = prs.slides.add_slide(bullet_layout)
        slide.shapes.title.text = heading
        tf = slide.placeholders[1].text_frame
        tf.clear()
        for idx, b in enumerate(bullets[:5]):
            p = tf.paragraphs[0] if idx == 0 else tf.add_paragraph()
            p.text = b.rstrip(".") + "."
            p.font.size = Pt(18)
            p.font.color.rgb = RGBColor(30, 41, 59)
            p.space_after = Pt(10)

    buf = io.BytesIO()
    prs.save(buf)
    buf.seek(0)
    return buf.getvalue()